import { useState } from "react";
import { Field as FUIField, Input } from "@fluentui/react-components";
import { z } from "zod/v4-mini";

import type { ClientSettings } from "../../../api/urbackupserver";
import textStyles from "../Form/TextField.module.css";
import { ClientSettingsTab, type SettingField } from "./ClientSettingsTab";
import { fromServerUrl, isValidServerUrl, toServerUrl } from "./internetServer";
import selectStyles from "./SelectDropdown.module.css";
import { KBIT_PER_S, SPEED_PATTERN, speedFormat } from "./timeSpan";

const MB = 1024 * 1024;

const dataplanField = (name: string, label: string): SettingField => ({
  name,
  label,
  kind: "text",
  pattern: /^\d*\.?\d*$/,
  format: {
    ui: (v) => String(Number(v) / MB),
    api: (v) => String(Math.round(Number(v) * MB)),
  },
});

function InternetServer({
  settings,
  validationMessage,
}: {
  settings: ClientSettings["settings"];
  validationMessage?: string;
}) {
  const all = settings as Record<string, { value?: unknown } | undefined>;

  const [url, setUrl] = useState(() =>
    toServerUrl(
      String(all.internet_server?.value ?? ""),
      String(all.internet_server_port?.value ?? ""),
    ),
  );

  const { server, port } = fromServerUrl(url);

  return (
    <>
      <input type="hidden" name="internet_server" value={server} />
      <input type="hidden" name="internet_server_port" value={port} />
      <FUIField
        label="Server URL clients connect to"
        hint="e.g. urbackup://backup.example.com, separate several with ';'"
        orientation="horizontal"
        className={textStyles.field}
        {...(validationMessage && {
          validationState: "error",
          validationMessage,
        })}
      >
        <Input
          className={selectStyles.select}
          value={url}
          onChange={(_, d) => setUrl(d.value)}
        />
      </FUIField>
    </>
  );
}

